package com.bbquantum.eazymanage.DTO.Attendance;

public class DatesMarked {

    private String dateMarked;

    private String dayMarked;

    private String staffName;

    public String getDateMarked() {
        return dateMarked;
    }

    public void setDateMarked(String dateMarked) {
        this.dateMarked = dateMarked;
    }

    public String getDayMarked() {
        return dayMarked;
    }

    public void setDayMarked(String dayMarked) {
        this.dayMarked = dayMarked;
    }

    public String getStaffName() {
        return staffName;
    }

    public void setStaffName(String staffName) {
        this.staffName = staffName;
    }
}
